// ข้อถัดไป วนกลับข้อแรกเมื่อครบ
export const nextTipIndex = (index: number, count: number) => (index + 1) % count;

// สุ่มข้อเริ่มต้น: รับตัวสุ่มเป็นพารามิเตอร์เพื่อทดสอบได้; ผลอยู่ในช่วง 0..count-1 เสมอ (แม้ตัวสุ่มคืนค่า 1)
export const randomTipIndex = (count: number, random: () => number = Math.random) =>
  count > 0 ? Math.min(count - 1, Math.floor(random() * count)) : 0;
